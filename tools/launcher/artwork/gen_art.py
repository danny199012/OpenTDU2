#!/usr/bin/env python3
"""OpenTDU2 launcher artwork generator.

Every image the launcher embeds - the Play hero, the five page banners and the
window icon - is generated by this script. The art is original to the project
and the provenance is this file: it draws sunsets over abstract coastlines with
Pillow only, and uses no game assets. Deterministic (fixed seeds), so a rerun
reproduces the exact same files:

    python gen_art.py     # writes hero_play.png, banner_*.png, opentdu2.ico

Replace any file with designed art later; launcher.rc.in just embeds whatever
sits here under these names.
"""

import math
import random

from PIL import Image, ImageDraw, ImageFilter


def lerp( a, b, t ):
    return tuple( int( a[i] + (b[i] - a[i]) * t ) for i in range( 3 ) )


def gradient_rows( img, y0, y1, c0, c1 ):
    d = ImageDraw.Draw( img )
    span = max( 1, y1 - y0 - 1 )
    for y in range( y0, y1 ):
        d.line( [( 0, y ), ( img.width, y )], fill=lerp( c0, c1, (y - y0) / span ) )


def add_overlay( img, overlay ):
    return Image.alpha_composite( img.convert( "RGBA" ), overlay ).convert( "RGB" )


def draw_sky( img, rng, pal, horizon ):
    gradient_rows( img, 0, horizon, pal["sky_top"], pal["sky_horizon"] )

    if pal.get( "stars" ):
        stars = Image.new( "RGBA", img.size, (0, 0, 0, 0) )
        sd = ImageDraw.Draw( stars )
        for _ in range( int( img.width * horizon / 1400 ) ):
            x, y = rng.uniform( 0, img.width ), rng.uniform( 0, horizon * 0.92 )
            sd.point( (x, y), fill=( 255, 255, 255, int( rng.uniform( 50, 190 ) ) ) )
        return stars, ImageDraw.Draw( img ), horizon
    return None, ImageDraw.Draw( img ), horizon


def draw_clouds( img, rng, pal, horizon ):
    clouds = Image.new( "RGBA", img.size, (0, 0, 0, 0) )
    cd = ImageDraw.Draw( clouds )
    for _ in range( pal.get( "clouds", 7 ) ):
        band = rng.uniform( 0.05, 0.75 )
        cx, cy = rng.uniform( 0, img.width ), horizon * band
        cw, ch = rng.uniform( img.width * 0.08, img.width * 0.3 ), rng.uniform( horizon * 0.02, horizon * 0.05 )
        cd.ellipse( [cx - cw, cy - ch, cx + cw, cy + ch], fill=pal["cloud"] + ( int( rng.uniform( 26, 60 ) ), ) )
    return clouds.filter( ImageFilter.GaussianBlur( img.width / 90 ) )


def draw_sun( img, pal, horizon ):
    glow = Image.new( "RGBA", img.size, (0, 0, 0, 0) )
    gd = ImageDraw.Draw( glow )
    sx, sy = img.width * pal["sun_x"], horizon * pal["sun_y"]
    for i in range( 60, 0, -1 ):
        r = i / 60 * img.width * pal["sun_glow"]
        gd.ellipse( [sx - r, sy - r, sx + r, sy + r],
                    fill=pal["sun_glow_color"] + ( int( 8 + 46 * (1 - i / 60) ), ) )
    glow = glow.filter( ImageFilter.GaussianBlur( img.width / 90 ) )
    img = add_overlay( img, glow )

    d = ImageDraw.Draw( img )
    r = img.width * pal["sun_r"]
    d.ellipse( [sx - r, sy - r, sx + r, sy + r], fill=pal["sun"] )
    return img, sx


def draw_sea( img, rng, pal, horizon, sx ):
    gradient_rows( img, horizon, img.height, pal["sea_far"], pal["sea_near"] )

    glitter = Image.new( "RGBA", img.size, (0, 0, 0, 0) )
    gd = ImageDraw.Draw( glitter )
    for _ in range( 240 ):
        t = rng.random()
        y = horizon + t * (img.height - horizon)
        spread = img.width * (0.004 + 0.05 * t)
        x = sx + rng.uniform( -spread, spread )
        ln = rng.uniform( 2, 16 * (0.3 + t) )
        gd.line( [( x, y ), ( x + ln, y )],
                 fill=pal["glitter"] + ( int( 90 * (1 - t) + 16 ), ), width=rng.randint( 1, 2 ) )

    waves = Image.new( "RGBA", img.size, (0, 0, 0, 0) )
    wd = ImageDraw.Draw( waves )
    for _ in range( int( img.width * (img.height - horizon) / 2400 ) ):
        y = rng.uniform( horizon + 4, img.height - 2 )
        depth = (y - horizon) / (img.height - horizon)
        x = rng.uniform( 0, img.width - 60 )
        ln = rng.uniform( 8, 46 ) * (0.4 + 0.6 * depth)
        wd.line( [( x, y ), ( x + ln, y )], fill=pal["wave"] + ( int( 30 * depth ) + 5, ), width=1 )

    return add_overlay( add_overlay( img, glitter ), waves )


def draw_ridge( img, rng, pal, horizon, side_left, width_frac, height, color=None ):
    """A headland silhouette rising from the horizon on one side."""
    d = ImageDraw.Draw( img )
    p1, p2 = rng.uniform( 0, 6.28 ), rng.uniform( 0, 6.28 )
    w = img.width * width_frac
    pts = []
    for i in range( 41 ):
        t = i / 40
        x = t * w if side_left else img.width - t * w
        # t runs frame-edge (0) -> inner edge (1) for both sides: taper at inner
        inner = 1 - t
        prof = ( 0.42 * math.sin( 2.4 * math.pi * t + p1 )
                 + 0.28 * math.sin( 3.9 * math.pi * t + p2 )
                 + 0.30 * math.sin( 0.9 * math.pi * t ) )
        y = horizon - max( 0.0, prof ) * height * min( 1.0, inner * 5.0 )
        pts.append( ( x, y ) )
    shore = ( pts[-1][0], horizon + 2 )
    pts.append( shore )
    pts.append( ( ( 0 if side_left else img.width ), horizon + 2 ) )
    d.polygon( pts, fill=color or pal["ridge"] )


def draw_boat( img, rng, pal, horizon ):
    d = ImageDraw.Draw( img )
    ink = pal["ridge"]
    bx = img.width * rng.uniform( 0.25, 0.8 )
    by = horizon + ( img.height - horizon ) * rng.uniform( 0.18, 0.4 )
    s = img.height * rng.uniform( 0.028, 0.04 )
    d.polygon( [( bx - s, by ), ( bx + s, by ), ( bx + s * 0.6, by + s * 0.32 ), ( bx - s * 0.6, by + s * 0.32 )], fill=ink )
    d.line( [( bx, by - s * 2.6 ), ( bx, by )], fill=ink, width=max( 1, int( s * 0.14 ) ) )
    d.polygon( [( bx, by - s * 2.6 ), ( bx, by - s * 0.1 ), ( bx + s * 0.95, by - s * 0.1 )], fill=ink )
    d.polygon( [( bx - s * 0.14, by - s * 2.1 ), ( bx - s * 0.14, by - s * 0.1 ), ( bx - s * 0.85, by - s * 0.1 )], fill=ink )


def vignette_and_grain( img, rng ):
    small = ( img.width // 3, img.height // 3 )
    mask = Image.new( "L", small, 0 )
    md = ImageDraw.Draw( mask )
    cx, cy = small[0] / 2, small[1] / 2
    far = math.hypot( cx, cy )
    for y in range( small[1] ):
        for x in range( 0, small[0], 2 ):
            t = max( 0.0, ( math.hypot( x - cx, y - cy ) / far - 0.55 ) / 0.45 )
            if t > 0:
                md.point( ( x, y ), fill=int( 110 * min( 1, t ) ) )
    mask = mask.resize( img.size ).filter( ImageFilter.GaussianBlur( img.width / 110 ) )
    shade = Image.new( "RGBA", img.size, ( 4, 8, 16, 255 ) )
    img = add_overlay( img, Image.composite( shade, Image.new( "RGBA", img.size, ( 0, 0, 0, 0 ) ), mask ) )

    noise = Image.effect_noise( img.size, 16 ).convert( "RGB" )
    return Image.blend( img, noise, 0.028 )


def coast_scene( w, h, seed, pal ):
    rng = random.Random( seed )
    horizon = int( h * pal.get( "horizon", 0.62 ) )
    img = Image.new( "RGB", ( w, h ), pal["sea_far"] )

    stars, d, _ = draw_sky( img, rng, pal, horizon )
    if stars:
        img = add_overlay( img, stars )
        d = ImageDraw.Draw( img )
    img = add_overlay( img, draw_clouds( img, rng, pal, horizon ) )
    img, sx = draw_sun( img, pal, horizon )
    img = draw_sea( img, rng, pal, horizon, sx )
    draw_ridge( img, rng, pal, horizon, pal.get( "ridge_left", True ), pal.get( "ridge_width", 0.34 ),
                horizon * pal.get( "ridge_height", 0.55 ) )
    if pal.get( "second_ridge" ):
        draw_ridge( img, rng, pal, horizon, not pal.get( "ridge_left", True ), pal.get( "ridge_width", 0.34 ) * 0.7,
                    horizon * pal.get( "ridge_height", 0.55 ) * 0.6, color=pal.get( "ridge_far" ) )
    if pal.get( "boat" ):
        draw_boat( img, rng, pal, horizon )
    return vignette_and_grain( img, rng )


