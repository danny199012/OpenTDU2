def make_icon( path ):
    s = 256
    base = Image.new( "RGBA", ( s, s ), ( 0, 0, 0, 0 ) )
    grad = Image.new( "RGBA", ( s, s ) )
    gd = ImageDraw.Draw( grad )
    for y in range( s ):
        gd.line( [( 0, y ), ( s, y )], fill=lerp( ( 20, 36, 61 ), ( 9, 19, 32 ), y / s ) + ( 255, ) )
    mask = Image.new( "L", ( s, s ), 0 )
    ImageDraw.Draw( mask ).rounded_rectangle( [8, 8, s - 8, s - 8], radius=52, fill=255 )
    base.paste( grad, ( 0, 0 ), mask )
    d = ImageDraw.Draw( base )
    d.rounded_rectangle( [8, 8, s - 8, s - 8], radius=52, outline=( 70, 100, 140, 190 ), width=2 )

    glow = Image.new( "RGBA", ( s, s ), ( 0, 0, 0, 0 ) )
    gld = ImageDraw.Draw( glow )
    for i in range( 40, 0, -1 ):
        r = i / 40 * 66
        gld.ellipse( [128 - r, 92 - r, 128 + r, 92 + r], fill=( 255, 170, 70, int( 8 + 40 * (1 - i / 40) ) ) )
    base = Image.alpha_composite( base, glow.filter( ImageFilter.GaussianBlur( 6 ) ) )
    d = ImageDraw.Draw( base )
    d.ellipse( [128 - 38, 92 - 38, 128 + 38, 92 + 38], fill=( 255, 182, 92, 255 ) )

    for j, ( y0, amp, alpha ) in enumerate( [ ( 148, 8, 235 ), ( 172, 10, 205 ), ( 196, 12, 175 ) ] ):
        pts = [ ( x, y0 + amp * math.sin( ( x / s ) * 4 * math.pi + j * 1.15 ) ) for x in range( 28, s - 27, 3 ) ]
        d.line( pts, fill=( 126, 208, 226, alpha ), width=7, joint="curve" )

    base.save( path, sizes=[ ( 256, 256 ), ( 128, 128 ), ( 64, 64 ), ( 48, 48 ),
                             ( 32, 32 ), ( 24, 24 ), ( 16, 16 ) ] )
    print( f"wrote {path}" )


