#!/usr/bin/env python3
"""Compiles the OpenTDU2 replacement GLSL shaders (resources/shaders) to SPIR-V
and embeds them as C++ arrays (source/render/shaders/builtin/*.h).

Requires glslangValidator (shipped with the Vulkan SDK). The generated headers
are committed, so this is only needed after editing a shader.

Pass shader file names to rebuild only those (the other headers are left alone:
a different glslang version would rewrite them all).
"""
import os, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'resources', 'shaders')
DST = os.path.join(ROOT, 'source', 'render', 'shaders', 'builtin')

# SPIR-V target environment per shader extension. The ray query compute shader
# needs SPIR-V 1.4 (VK_KHR_spirv_1_4, enabled on the Vulkan 1.1 device):
# '--target-env vulkan1.2' would emit SPIR-V 1.5 instead, which the device
# rejects, and 'vulkan1.1' cannot express ray queries at all.
TARGET_ENV = {'.vert': 'vulkan1.1', '.frag': 'vulkan1.1', '.comp': 'spirv1.4'}

# HLSL sources (compiled with dxc from the Vulkan SDK): file -> [(entry point, output name)].
# The output is a pixel shader, named like a .frag so the C++ side reads the same.
HLSL = {'fsr1.hlsl': [('EASU', 'fsr1_easu.frag'), ('RCAS', 'fsr1_rcas.frag')]}
HLSL_INCLUDE = os.path.join(ROOT, 'third_party', 'fidelityfx-fsr1')

def emit(name, data):
    ident = 'kSPIRV_' + name.replace('.', '_')
    words = [int.from_bytes(data[i:i+4], 'little') for i in range(0, len(data), 4)]
    lines = ['// Generated by tools/compile_shaders.py. Do not edit.',
             '#pragma once', '', 'static const uint32_t %s[] = {' % ident]
    for i in range(0, len(words), 8):
        lines.append('    ' + ', '.join('0x%08x' % w for w in words[i:i+8]) + ',')
    lines.append('};')
    out = os.path.join(DST, name.replace('.', '_') + '.h')
    with open(out, 'w', newline='\n') as header:
        header.write('\n'.join(lines) + '\n')
    print('%s -> %s (%d bytes)' % (name, os.path.relpath(out, ROOT), len(data)))

def compile_hlsl(only):
    for src_name, entries in HLSL.items():
        if only and src_name not in only:
            continue
        for entry, out_name in entries:
            with tempfile.TemporaryDirectory() as tmp:
                spv = os.path.join(tmp, 'out.spv')
                subprocess.check_call(['dxc', '-spirv', '-T', 'ps_6_2', '-E', entry, '-fspv-target-env=vulkan1.1', '-fspv-entrypoint-name=main',
                                       '-I', HLSL_INCLUDE, os.path.join(SRC, src_name), '-Fo', spv])
                emit(out_name, open(spv, 'rb').read())

def main():
    only = set(sys.argv[1:])
    os.makedirs(DST, exist_ok=True)
    compile_hlsl(only)
    for name in sorted(os.listdir(SRC)):
        ext = os.path.splitext(name)[1]
        if ext not in TARGET_ENV:
            continue
        if only and name not in only:
            continue
        src = os.path.join(SRC, name)
        with tempfile.TemporaryDirectory() as tmp:
            spv = os.path.join(tmp, 'out.spv')
            subprocess.check_call(['glslangValidator', '-V', '--target-env', TARGET_ENV[ext], '-o', spv, src])
            data = open(spv, 'rb').read()
        ident = 'kSPIRV_' + name.replace('.', '_')
        words = [int.from_bytes(data[i:i+4], 'little') for i in range(0, len(data), 4)]
        lines = ['// Generated by tools/compile_shaders.py from resources/shaders/%s. Do not edit.' % name,
                 '#pragma once', '', 'static const uint32_t %s[] = {' % ident]
        for i in range(0, len(words), 8):
            lines.append('    ' + ', '.join('0x%08x' % w for w in words[i:i+8]) + ',')
        lines.append('};')
        out = os.path.join(DST, name.replace('.', '_') + '.h')
        # newline='\n': the repository is LF only (.gitattributes eol=lf), and
        # text mode would otherwise write CRLF on Windows.
        with open(out, 'w', newline='\n') as header:
            header.write('\n'.join(lines) + '\n')
        print('%s -> %s (%d bytes)' % (name, os.path.relpath(out, ROOT), len(data)))

if __name__ == '__main__':
    main()
