#!/usr/bin/env python3
"""Generates the tuner-garage mod's spoiler meshes (our own art, no game data).

Blender convention, which is what the in-game OBJ loader expects
(source/game/spots/mod_props.cpp): right handed, Y up, -Z forward. The loader
mirrors X and reverses the winding itself, so a plain correct OBJ authored
here lands the same way round as a retail mesh. Y=0 is the deck plane the part
sits on; the car's nose is toward -Z.

  python tools/mod/make_gt_wing.py   # writes into the tuner-garage package

Outputs (resources/mods/packages/tuner-garage/tuner/parts/):
  wing_gt.obj        a full GT wing: airfoil blade, two uprights, endplates
  wing_ducktail.obj  a ducktail lip (the classic 911 / Le Mans look)
  wing_street.obj    a subtle street lip
Each is one material (carbon), a few hundred triangles, plain OBJ with uvs
and flat normals.
"""
import math
import os
import sys

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
                       "resources", "mods", "packages", "tuner-garage", "tuner", "parts")

CARBON = (0.045, 0.048, 0.055)  # near-black carbon


# ---------------------------------------------------------------------------
# tiny OBJ builder
# ---------------------------------------------------------------------------

class Obj:
    def __init__(self):
        self.verts = []    # (x, y, z)
        self.uvs = []      # (u, v), parallel to verts
        self.normals = []  # (x, y, z)
        self.faces = []    # (vi, ti, ni) triples, one triangle per 3 entries

    def v(self, x, y, z):
        self.verts.append((x, y, z))
        self.uvs.append((0.5 + x, 0.5 + z))  # a harmless planar map (no texture)
        return len(self.verts)               # 1-based index

    def add_normal(self, n):
        self.normals.append(n)
        return len(self.normals)

    def tri(self, a, b, c, ni):
        self.faces.append((a, b, c, ni))

    def quad(self, a, b, c, d, ni):
        self.faces.append((a, b, c, ni))
        self.faces.append((a, c, d, ni))

    def write(self, name):
        # self-check: every face index must be a real vertex
        for (a, b, c, ni) in self.faces:
            for vi in (a, b, c):
                assert 1 <= vi <= len(self.verts), f"{name}: face index {vi} of {len(self.verts)}"
        with open(os.path.join(OUT_DIR, name + ".obj"), "w") as f:
            f.write("# generated by tools/mod/make_gt_wing.py - our own art\n")
            f.write(f"mtllib {name}.mtl\n")
            f.write("usemtl carbon\n")
            for x, y, z in self.verts:
                f.write(f"v {x:.5f} {y:.5f} {z:.5f}\n")
            for u, v in self.uvs:
                f.write(f"vt {u:.4f} {v:.4f}\n")
            for x, y, z in self.normals:
                f.write(f"vn {x:.4f} {y:.4f} {z:.4f}\n")
            for a, b, c, ni in self.faces:
                f.write(f"f {a}/{a}/{ni} {b}/{b}/{ni} {c}/{c}/{ni}\n")
        with open(os.path.join(OUT_DIR, name + ".mtl"), "w") as f:
            f.write("# generated by tools/mod/make_gt_wing.py\n")
            f.write("newmtl carbon\n")
            f.write(f"Kd {CARBON[0]:.4f} {CARBON[1]:.4f} {CARBON[2]:.4f}\n")
            f.write("map_Kd carbon.png\n")
            f.write("Ka 0.12 0.12 0.12\n")
            f.write("Ks 0.35 0.35 0.35\n")
            f.write("Ns 60\n")
            f.write("d 1.0\n")
        print(f"  {name}: {len(self.verts)} verts, {len(self.faces)} triangles")


# ---------------------------------------------------------------------------
# solid builders
# ---------------------------------------------------------------------------

def extrude_profile(obj, profile, x0, x1):
    """Extrudes a closed 2D profile ([(z, y)], wound CCW seen from +X) along X
    from x0 to x1, with flat-shaded sides and capped ends."""
    n = len(profile)
    base = len(obj.verts) + 1  # the 1-based index of the first new vertex
    for x in (x0, x1):
        for (z, y) in profile:
            obj.v(x, y, z)
    for i in range(n):
        j = (i + 1) % n
        z0, y0 = profile[i]
        z1, y1 = profile[j]
        ez, ey = z1 - z0, y1 - y0
        nz, ny = ey, -ez  # outward for a CCW ring seen from +X
        ln = math.hypot(nz, ny) or 1.0
        ni = obj.add_normal((0.0, ny / ln, nz / ln))
        obj.quad(base + i, base + j, base + n + j, base + n + i, ni)
    for x_idx, winding in ((0, -1), (1, 1)):  # x0 faces -X, x1 faces +X
        cx = sum(p[0] for p in profile) / n
        cy = sum(p[1] for p in profile) / n
        ni = obj.add_normal((float(winding), 0.0, 0.0))
        center = obj.v(x0 if x_idx == 0 else x1, cy, cx)
        for i in range(n):
            j = (i + 1) % n
            a = base + (i if x_idx == 0 else n + i)
            b = base + (j if x_idx == 0 else n + j)
            if winding == 1:
                obj.tri(center, a, b, ni)
            else:
                obj.tri(center, b, a, ni)


def box(obj, cx, cz, size_x, size_z, y0, y1):
    """A box centred on (cx, cz) in the X/Z plane, from y0 to y1."""
    hx, hz = size_x / 2.0, size_z / 2.0
    corners = [(cx - hx, cz - hz), (cx + hx, cz - hz), (cx + hx, cz + hz), (cx - hx, cz + hz)]
    base = len(obj.verts) + 1  # the 1-based index of the first new vertex
    for y in (y0, y1):
        for (x, z) in corners:
            obj.v(x, y, z)
    for i in range(4):
        j = (i + 1) % 4
        x0, z0 = corners[i]
        x1, z1 = corners[j]
        nx, nz = z1 - z0, -(x1 - x0)  # outward for CCW-seen-from-above corners
        ln = math.hypot(nx, nz) or 1.0
        ni = obj.add_normal((nx / ln, 0.0, nz / ln))
        obj.quad(base + i, base + j, base + 4 + j, base + 4 + i, ni)
    obj.quad(base, base + 1, base + 2, base + 3, obj.add_normal((0.0, -1.0, 0.0)))
    obj.quad(base + 4, base + 7, base + 6, base + 5, obj.add_normal((0.0, 1.0, 0.0)))


def airfoil_profile(chord, thickness, camber=0.0, points=12):
    """A closed airfoil ring [(z, y)] wound CCW seen from +X: upper surface
    traversed trailing -> leading, lower back leading -> trailing. Leading
    edge at z = -chord/2 (the car's nose side)."""
    zs = [-chord / 2.0 * math.cos(math.pi * i / points) for i in range(points + 1)]  # leading..trailing
    upper, lower = [], []
    for z in zs:
        tt = 1.0 - abs(z) / (chord / 2.0)
        yt = 5.0 * thickness * (0.2969 * math.sqrt(tt) - 0.1260 * tt - 0.3516 * tt * tt
                                + 0.2843 * tt ** 3 - 0.1036 * tt ** 4) * chord
        yc = camber * chord * math.sin(math.pi * tt * 0.85)
        upper.append((z, yc + yt))
        lower.append((z, yc - yt))
    return upper[::-1] + lower


# ---------------------------------------------------------------------------
# the parts
# ---------------------------------------------------------------------------

def wing_gt():
    """Full GT wing: a 1.62 m airfoil blade on two uprights, endplates.
    Origin: the deck plane (y=0), chord centre at z=0."""
    obj = Obj()
    blade_y, chord, thick = 0.205, 0.335, 0.11
    profile = [(z, blade_y + y) for (z, y) in airfoil_profile(chord, thick, camber=-0.06)]
    extrude_profile(obj, profile, -0.81, 0.81)
    for sx in (-0.30, 0.30):
        box(obj, sx, -0.030, 0.135, 0.038, 0.0, blade_y + thick * 0.3)  # upright
        box(obj, sx, -0.055, 0.135, 0.030, 0.0, 0.018)                  # foot
    for sx in (-0.815, 0.815):
        box(obj, sx, 0.0, 0.012, chord + 0.03, blade_y - 0.055, blade_y + thick + 0.055)
    obj.write("wing_gt")


def wing_ducktail():
    """Ducktail lip: a curved lip rising off the deck, flush-mounted.
    Origin: its front-bottom edge (z=0), rising toward -Z (the rear: the car
    body space has the nose at +Z)."""
    obj = Obj()
    width, depth, height = 1.52, 0.26, 0.075
    steps = 8
    top, bottom = [], []
    for i in range(steps + 1):
        t = i / steps
        z = -depth * t
        y = height * (t * t * (3 - 2 * t))  # smoothstep
        top.append((z, y))
        bottom.append((z, max(0.0, y - 0.03 - 0.012 * math.sin(math.pi * t))))
    extrude_profile(obj, top + bottom[::-1], -width / 2.0, width / 2.0)
    obj.write("wing_ducktail")


def wing_street():
    """Street lip: a subtle low blade on two small risers.
    Origin: the deck plane, blade rises to ~0.06 m."""
    obj = Obj()
    width, blade_y = 1.56, 0.052
    profile = [(z, blade_y + y + 0.012) for (z, y) in airfoil_profile(0.19, 0.09)]
    extrude_profile(obj, profile, -width / 2.0, width / 2.0)
    for sx in (-0.52, 0.52):
        box(obj, sx, 0.0, 0.11, 0.045, 0.0, blade_y + 0.012)
    obj.write("wing_street")


def carbon_texture():
    """A 64x64 near-black carbon weave (our art): the untextured TD_Gouraud
    route renders white, so every part maps this."""
    path = os.path.join(OUT_DIR, "carbon.png")
    width = height = 64
    rows = bytearray()
    for y in range(height):
        for x in range(width):
            # a 4px twill weave: brighter strands on the diagonals
            strand = ((x + y) % 8) < 4
            base = 26 if strand else 14
            jitter = (x * 7 + y * 13) % 5
            value = base + jitter
            rows += bytes((value, value, value + 2, 255))
    import struct
    import zlib

    def chunk(tag, data):
        out = struct.pack(">I", len(data)) + tag + data
        return out + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    raw = b"".join(b"\x00" + bytes(rows[y * width * 4:(y + 1) * width * 4]) for y in range(height))
    png = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw)) +
           chunk(b"IEND", b""))
    with open(path, "wb") as f:
        f.write(png)
    print(f"  carbon.png ({width}x{height})")


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    print(f"Writing parts into {os.path.abspath(OUT_DIR)}")
    carbon_texture()
    wing_gt()
    wing_ducktail()
    wing_street()


if __name__ == "__main__":
    sys.exit(main())
