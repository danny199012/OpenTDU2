def extrude_profile(obj, profile, x0, x1):
    """Extrudes a closed 2D profile ([(z, y)], wound CCW seen from +X) along X
    from x0 to x1, with flat-shaded sides and capped ends."""
    n = len(profile)
    base = len(obj.verts) + 1  # the 1-based index of the first new vertex
    for x in (x0, x1):
        for (z, y) in profile:
            obj.v(x, y, z)
    for i in range(n):
        j = (i + 1) % n
        z0, y0 = profile[i]
        z1, y1 = profile[j]
        ez, ey = z1 - z0, y1 - y0
        nz, ny = ey, -ez  # outward for a CCW ring seen from +X
        ln = math.hypot(nz, ny) or 1.0
        ni = obj.add_normal((0.0, ny / ln, nz / ln))
        obj.quad(base + i, base + j, base + n + j, base + n + i, ni)
    for x_idx, winding in ((0, -1), (1, 1)):  # x0 faces -X, x1 faces +X
        cx = sum(p[0] for p in profile) / n
        cy = sum(p[1] for p in profile) / n
        ni = obj.add_normal((float(winding), 0.0, 0.0))
        center = obj.v(x0 if x_idx == 0 else x1, cy, cx)
        for i in range(n):
            j = (i + 1) % n
            a = base + (i if x_idx == 0 else n + i)
            b = base + (j if x_idx == 0 else n + j)
            if winding == 1:
                obj.tri(center, a, b, ni)
            else:
                obj.tri(center, b, a, ni)


def box(obj, cx, cz, size_x, size_z, y0, y1):
    """A box centred on (cx, cz) in the X/Z plane, from y0 to y1."""
    hx, hz = size_x / 2.0, size_z / 2.0
    corners = [(cx - hx, cz - hz), (cx + hx, cz - hz), (cx + hx, cz + hz), (cx - hx, cz + hz)]
    base = len(obj.verts) + 1  # the 1-based index of the first new vertex
    for y in (y0, y1):
        for (x, z) in corners:
            obj.v(x, y, z)
    for i in range(4):
        j = (i + 1) % 4
        x0, z0 = corners[i]
        x1, z1 = corners[j]
        nx, nz = z1 - z0, -(x1 - x0)  # outward for CCW-seen-from-above corners
        ln = math.hypot(nx, nz) or 1.0
        ni = obj.add_normal((nx / ln, 0.0, nz / ln))
        obj.quad(base + i, base + j, base + 4 + j, base + 4 + i, ni)
    obj.quad(base, base + 1, base + 2, base + 3, obj.add_normal((0.0, -1.0, 0.0)))
    obj.quad(base + 4, base + 7, base + 6, base + 5, obj.add_normal((0.0, 1.0, 0.0)))


def airfoil_profile(chord, thickness, camber=0.0, points=12):
    """A closed airfoil ring [(z, y)] wound CCW seen from +X: upper surface
    traversed trailing -> leading, lower back leading -> trailing. Leading
    edge at z = -chord/2 (the car's nose side)."""
    zs = [-chord / 2.0 * math.cos(math.pi * i / points) for i in range(points + 1)]  # leading..trailing
    upper, lower = [], []
    for z in zs:
        tt = 1.0 - abs(z) / (chord / 2.0)
        yt = 5.0 * thickness * (0.2969 * math.sqrt(tt) - 0.1260 * tt - 0.3516 * tt * tt
                                + 0.2843 * tt ** 3 - 0.1036 * tt ** 4) * chord
        yc = camber * chord * math.sin(math.pi * tt * 0.85)
        upper.append((z, yc + yt))
        lower.append((z, yc - yt))
    return upper[::-1] + lower


