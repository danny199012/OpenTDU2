def wing_gt():
    """Full GT wing: a 1.62 m airfoil blade on two uprights, endplates.
    Origin: the deck plane (y=0), chord centre at z=0."""
    obj = Obj()
    blade_y, chord, thick = 0.205, 0.335, 0.11
    profile = [(z, blade_y + y) for (z, y) in airfoil_profile(chord, thick, camber=-0.06)]
    extrude_profile(obj, profile, -0.81, 0.81)
    for sx in (-0.30, 0.30):
        box(obj, sx, -0.030, 0.135, 0.038, 0.0, blade_y + thick * 0.3)  # upright
        box(obj, sx, -0.055, 0.135, 0.030, 0.0, 0.018)                  # foot
    for sx in (-0.815, 0.815):
        box(obj, sx, 0.0, 0.012, chord + 0.03, blade_y - 0.055, blade_y + thick + 0.055)
    obj.write("wing_gt")


def wing_ducktail():
    """Ducktail lip: a curved lip rising off the deck, flush-mounted.
    Origin: its front-bottom edge (z=0), rising toward -Z (the rear: the car
    body space has the nose at +Z)."""
    obj = Obj()
    width, depth, height = 1.52, 0.26, 0.075
    steps = 8
    top, bottom = [], []
    for i in range(steps + 1):
        t = i / steps
        z = -depth * t
        y = height * (t * t * (3 - 2 * t))  # smoothstep
        top.append((z, y))
        bottom.append((z, max(0.0, y - 0.03 - 0.012 * math.sin(math.pi * t))))
    extrude_profile(obj, top + bottom[::-1], -width / 2.0, width / 2.0)
    obj.write("wing_ducktail")


def wing_street():
    """Street lip: a subtle low blade on two small risers.
    Origin: the deck plane, blade rises to ~0.06 m."""
    obj = Obj()
    width, blade_y = 1.56, 0.052
    profile = [(z, blade_y + y + 0.012) for (z, y) in airfoil_profile(0.19, 0.09)]
    extrude_profile(obj, profile, -width / 2.0, width / 2.0)
    for sx in (-0.52, 0.52):
        box(obj, sx, 0.0, 0.11, 0.045, 0.0, blade_y + 0.012)
    obj.write("wing_street")


def wing_blade():
    """Evo-style low blade: a shallow wide blade on short risers, small
    endplates (the rally-wing silhouette). Origin: the deck plane."""
    obj = Obj()
    blade_y, chord, thick = 0.115, 0.185, 0.075
    profile = [(z, blade_y + y) for (z, y) in airfoil_profile(chord, thick, camber=-0.10)]
    extrude_profile(obj, profile, -0.79, 0.79)
    for sx in (-0.48, 0.48):
        box(obj, sx, 0.005, 0.10, 0.035, 0.0, blade_y)      # riser
        box(obj, sx, -0.01, 0.16, 0.045, 0.0, 0.014)        # foot
    for sx in (-0.795, 0.795):
        box(obj, sx, 0.0, 0.010, chord + 0.025, blade_y - 0.03, blade_y + thick + 0.04)
    obj.write("wing_blade")


def wing_swan():
    """Swan-neck wing: a wide airfoil hung UNDER two curved pylons (the
    race-car look: the blade's lower surface stays clean). Origin: deck plane."""
    obj = Obj()
    blade_y, chord, thick = 0.27, 0.30, 0.10
    profile = [(z, blade_y + y) for (z, y) in airfoil_profile(chord, thick, camber=-0.05)]
    extrude_profile(obj, profile, -0.83, 0.83)
    for sx in (-0.34, 0.34):
        # the pylon: a swan neck, leaning back as it rises, joining the blade top
        steps = 7
        prev = None
        for i in range(steps + 1):
            t = i / steps
            y = blade_y + thick * 0.9 - t * (blade_y + thick * 0.9 - 0.0)
            z = -0.04 - 0.07 * math.sin(math.pi * t)  # bows rearward
            if prev is not None:
                zc, yc = (prev[0] + z) / 2.0, (prev[1] + y) / 2.0
                box(obj, sx, zc, 0.07, 0.035, min(prev[1], y), max(prev[1], y) + 0.012)
            prev = (z, y)
        box(obj, sx, -0.04, 0.12, 0.05, 0.0, 0.016)  # foot
    for sx in (-0.835, 0.835):
        box(obj, sx, 0.0, 0.010, chord + 0.04, blade_y - 0.07, blade_y + thick + 0.07)
    obj.write("wing_swan")


def wing_dual():
    """Dual-element wing: a main blade with a flap above it, tall endplates."""
    obj = Obj()
    main_y, flap_y = 0.30, 0.43
    main = [(z, main_y + y) for (z, y) in airfoil_profile(0.34, 0.10, camber=-0.06)]
    flap = [(z - 0.02, flap_y + y) for (z, y) in airfoil_profile(0.20, 0.08, camber=-0.10)]
    extrude_profile(obj, main, -0.80, 0.80)
    extrude_profile(obj, flap, -0.80, 0.80)
    for sx in (-0.28, 0.28):
        box(obj, sx, -0.03, 0.12, 0.04, 0.0, main_y + 0.03)
        box(obj, sx, -0.06, 0.12, 0.03, 0.0, 0.018)
    for sx in (-0.81, 0.81):
        box(obj, sx, -0.01, 0.014, 0.42, main_y - 0.08, flap_y + 0.13)
    obj.write("wing_dual")


