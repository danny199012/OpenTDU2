def png(path, width, height, pixel):
    import struct
    import zlib
    rows = bytearray()
    for y in range(height):
        for x in range(width):
            rows += bytes(pixel(x, y))

    def chunk(tag, data):
        out = struct.pack(">I", len(data)) + tag + data
        return out + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    raw = b"".join(b"\x00" + bytes(rows[y * width * 4:(y + 1) * width * 4]) for y in range(height))
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw)) +
                chunk(b"IEND", b""))


def metal_textures():
    """The finishes, painted to the tip UV layout: u (texture x) wraps around
    the tube - 0.75 the top, 0.25 the bottom, the horizon at 0.0 / 0.5 - and
    v (texture y) runs along the pipe (0 = the mouth). chrome: sky over the
    top of the tube, road below, sharp horizon. titanium: burnt violet at the
    mouth -> blue -> gold, black throat. carbonsteel: the carbon weave shell
    with a polished bore. Every finish goes near-black past v 0.85 (the
    throat)."""
    W = H = 64

    def chrome(x, y):
        t = y / float(H - 1)
        if t > 0.85:
            v = 26 + (x % 4)                        # the dark throat
        else:
            d = abs(x / float(W - 1) - 0.75)        # angular distance from the top
            if d < 0.25:                            # sky, brightest at the very top
                v = 190 - int(120 * (0.25 - d) / 0.25)
            else:                                   # road
                v = 34 + int(26 * (d - 0.25) / 0.25)
        n = (x * 3 + y * 5) % 7 - 3
        v = max(0, min(255, v + n))
        return (v, v, min(255, v + 5), 255)

    def burnt(stops):
        def pixel(x, y):
            t = y / float(H - 1)                    # along the pipe
            for k in range(len(stops) - 1):
                t0, c0 = stops[k]
                t1, c1 = stops[k + 1]
                if t <= t1 or k == len(stops) - 2:
                    f = 0.0 if t1 <= t0 else min(1.0, max(0.0, (t - t0) / (t1 - t0)))
                    c = tuple(int(c0[i] + (c1[i] - c0[i]) * f) for i in range(3))
                    break
            # the faint burn rings: a slow sinusoid along the pipe
            ring = int(7 * math.sin(t * 40.0))
            n = ((x * 5 + y * 11) % 9 - 4) + ring
            return (max(0, c[0] + n), max(0, c[1] + n), max(0, c[2] + n), 255)
        return pixel

    def ceramic(x, y):
        # near-black ceramic coat with a soft top sheen
        d = abs(x / float(W - 1) - 0.75)            # angular distance from the top
        v = 30 + int(34 * max(0.0, 1.0 - d / 0.30)) + (x * 3 % 5)
        return (v, v, min(255, v + 3), 255)

    # burnt titanium, kept dark and muted so it reads as heat-stained metal,
    # not candy: violet-blue at the rim, bronze-gold further in
    titanium = burnt([(0.00, (88, 66, 132)), (0.08, (76, 86, 148)),
                      (0.24, (128, 122, 112)), (0.46, (172, 138, 86)),
                      (0.72, (186, 156, 94)), (0.86, (30, 25, 28)),
                      (1.00, (22, 18, 20))])
    # the deep-blue burnt: a saturated blue rim over the gold (the show-car
    # burnt look of the owner's reference photo)
    titanium_blue = burnt([(0.00, (46, 62, 185)), (0.16, (66, 92, 190)),
                           (0.34, (128, 128, 120)), (0.55, (178, 144, 86)),
                           (0.76, (200, 162, 82)), (0.86, (30, 25, 28)),
                           (1.00, (22, 18, 20))])

    def carbonsteel(x, y):
        t = y / float(H - 1)
        if t <= 0.25:                               # the weave shell
            strand = ((x + y) % 8) < 4
            value = (30 if strand else 16) + (x * 7 + y * 13) % 5
            return (value, value, value + 2, 255)
        if t < 0.32:
            return (10, 10, 11, 255)                # the shell / bore shadow line
        if t <= 0.82:                               # the polished bore
            d = abs(t - 0.55)
            v = max(70, 210 - int(150 * d / 0.27)) + (x * 3 % 5)
            return (v, v, min(255, v + 6), 255)
        return (16, 14, 15, 255)                    # the dark throat

    png(os.path.join(OUT_DIR, "chrome.png"), W, H, chrome)
    png(os.path.join(OUT_DIR, "titanium.png"), W, H, titanium)
    png(os.path.join(OUT_DIR, "titanium_blue.png"), W, H, titanium_blue)
    png(os.path.join(OUT_DIR, "carbonsteel.png"), W, H, carbonsteel)
    png(os.path.join(OUT_DIR, "ceramic.png"), W, H, ceramic)
    print(f"  chrome.png, titanium.png, titanium_blue.png, carbonsteel.png, ceramic.png ({W}x{H})")


def carbon_texture():
    """A 64x64 near-black carbon weave (our art): the untextured TD_Gouraud
    route renders white, so every part maps this."""
    path = os.path.join(OUT_DIR, "carbon.png")
    width = height = 64
    rows = bytearray()
    for y in range(height):
        for x in range(width):
            # a 4px twill weave: brighter strands on the diagonals
            strand = ((x + y) % 8) < 4
            base = 26 if strand else 14
            jitter = (x * 7 + y * 13) % 5
            value = base + jitter
            rows += bytes((value, value, value + 2, 255))
    import struct
    import zlib

    def chunk(tag, data):
        out = struct.pack(">I", len(data)) + tag + data
        return out + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    raw = b"".join(b"\x00" + bytes(rows[y * width * 4:(y + 1) * width * 4]) for y in range(height))
    png = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw)) +
           chunk(b"IEND", b""))
    with open(path, "wb") as f:
        f.write(png)
    print(f"  carbon.png ({width}x{height})")


